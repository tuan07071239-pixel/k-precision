/**
 * Apply translations to the current page based on selected language
 */
function applyLanguage(lang) {
  const t = window.KP_TRANSLATIONS[lang];
  if (!t) return;

  // Set html lang attribute
  document.documentElement.lang = lang === 'ko' ? 'ko' : lang === 'vi' ? 'vi' : 'en';

  // Apply textContent keys
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // Apply placeholder keys
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) {
      el.placeholder = t[key].replace(/&amp;/g, '&');
    }
  });

  // Update lang switcher buttons
  document.querySelectorAll('.kp-lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Save to localStorage
  localStorage.setItem('kp-lang', lang);
}

/**
 * Initialize i18n on page load
 */
function initI18n() {
  const saved = localStorage.getItem('kp-lang') || 'en';
  applyLanguage(saved);

  // Bind language switcher buttons
  document.querySelectorAll('.kp-lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      const lang = btn.getAttribute('data-lang');
      if (lang) applyLanguage(lang);
    });
  });
}

window.KP_I18N = { apply: applyLanguage, init: initI18n };
