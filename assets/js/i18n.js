const LANG_CONFIG = {
  en: { flag: "🇺🇸", label: "EN" },
  ko: { flag: "🇰🇷", label: "KO" },
  vi: { flag: "🇻🇳", label: "VI" }
};

/**
 * Intelligent DOM Auto-Translator
 * Automatically sweeps text nodes, buttons, badges, specs, breadcrumbs, and tables
 */
function applyAutoTranslations(lang) {
  const targetMap = UI_AUTO_MAP[lang];

  // Candidates: buttons, links, spans, th, strong, spec labels, badges, breadcrumbs
  const selector = 'button, a, .category-badge, .section-tag, .product-badge-corner, .spec-name, th, .breadcrumbs a, .breadcrumbs .current, .quick-spec-label, .rfq-summary-row span, .rfq-empty-state p, .btn-submit-rfq, .rfq-clear-btn';
  
  document.querySelectorAll(selector).forEach(el => {
    // Do not alter elements that have their own data-i18n
    if (el.hasAttribute('data-i18n')) return;
    // Don't modify language switcher elements
    if (el.closest('.kp-lang-dropdown') || el.closest('.kp-lang-switcher')) return;

    // Cache original English text
    if (!el.dataset.i18nOrig) {
      el.dataset.i18nOrig = el.textContent.trim();
    }

    const orig = el.dataset.i18nOrig;

    if (lang === 'en') {
      // Restore original English text if mapped
      if (orig && (targetMap || UI_AUTO_MAP['ko'][orig] || UI_AUTO_MAP['vi'][orig])) {
        el.textContent = orig;
      }
    } else if (targetMap && targetMap[orig]) {
      el.textContent = targetMap[orig];
    }
  });
}

/**
 * Main application function for language switching
 */
function applyLanguage(lang) {
  if (!window.KP_TRANSLATIONS || !window.KP_TRANSLATIONS[lang]) {
    lang = 'en';
  }

  const t = window.KP_TRANSLATIONS[lang];

  // 1. Apply explicit [data-i18n] keys
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t && t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // 2. Apply [data-i18n-placeholder] attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t && t[key] !== undefined) {
      el.placeholder = t[key];
    }
  });

  // 3. Apply Intelligent DOM Auto-Translation
  applyAutoTranslations(lang);

  // 4. Update dropdown UI
  const conf = LANG_CONFIG[lang] || LANG_CONFIG.en;
  document.querySelectorAll('.kp-lang-dropdown').forEach(dd => {
    const flagEl = dd.querySelector('.kp-lang-current-flag');
    const labelEl = dd.querySelector('.kp-lang-current-label');
    if (flagEl) flagEl.textContent = conf.flag;
    if (labelEl) labelEl.textContent = conf.label;

    dd.querySelectorAll('.kp-lang-item').forEach(item => {
      const itemLang = item.getAttribute('data-lang');
      item.classList.toggle('active', itemLang === lang);
    });
  });

  // 5. Update legacy buttons if present
  document.querySelectorAll('.kp-lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // 6. Save preference
  localStorage.setItem('kp-lang', lang);

  // 7. Dispatch event for other components
  window.dispatchEvent(new CustomEvent('kp-language-change', { detail: { lang: lang } }));
}

let _i18nEventsBound = false;

/**
 * Initialize i18n on page load
 */
function initI18n() {
  const saved = localStorage.getItem('kp-lang') || 'en';
  applyLanguage(saved);

  if (_i18nEventsBound) return;
  _i18nEventsBound = true;

  // Dropdown toggle
  document.querySelectorAll('.kp-lang-dropdown-btn').forEach(btn => {
    if (btn.dataset.i18nBound) return;
    btn.dataset.i18nBound = 'true';
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      const dropdown = btn.closest('.kp-lang-dropdown');
      if (dropdown) {
        const isOpen = dropdown.classList.toggle('open');
        btn.setAttribute('aria-expanded', isOpen);
      }
    });
  });

  // Dropdown item selection
  document.querySelectorAll('.kp-lang-item').forEach(item => {
    if (item.dataset.i18nBound) return;
    item.dataset.i18nBound = 'true';
    item.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      const lang = item.getAttribute('data-lang');
      if (lang) {
        applyLanguage(lang);
      }
      const dropdown = item.closest('.kp-lang-dropdown');
      if (dropdown) {
        dropdown.classList.remove('open');
        dropdown.querySelector('.kp-lang-dropdown-btn')?.setAttribute('aria-expanded', 'false');
      }
    });
  });

  // Close dropdown when clicking outside
  document.addEventListener('click', (e) => {
    if (!e.target.closest('.kp-lang-dropdown')) {
      document.querySelectorAll('.kp-lang-dropdown.open').forEach(dropdown => {
        dropdown.classList.remove('open');
        dropdown.querySelector('.kp-lang-dropdown-btn')?.setAttribute('aria-expanded', 'false');
      });
    }
  });

  // Close on Escape key
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      document.querySelectorAll('.kp-lang-dropdown.open').forEach(dropdown => {
        dropdown.classList.remove('open');
        dropdown.querySelector('.kp-lang-dropdown-btn')?.setAttribute('aria-expanded', 'false');
      });
    }
  });
}

window.KP_I18N = {
  apply: applyLanguage,
  init: initI18n,
  autoTranslate: applyAutoTranslations
};

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
