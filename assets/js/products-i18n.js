/**
 * Returns a localized copy of a product object based on target language
 */
window.getLocalizedProduct = function(product, lang) {
  if (!product) return null;
  if (!lang || lang === 'en' || !window.KP_PRODUCT_TRANSLATIONS || !window.KP_PRODUCT_TRANSLATIONS[lang]) {
    return product;
  }

  const t = window.KP_PRODUCT_TRANSLATIONS[lang][product.sku];
  if (!t) return product;

  const loc = {
    ...product,
    name: t.name || product.name,
    badge: t.badge || product.badge,
    category: t.category || product.category,
    shortDesc: t.shortDesc || product.shortDesc,
    purpose: t.purpose || product.purpose,
    workpieceMaterials: t.workpieceMaterials || product.workpieceMaterials,
    keyFeatures: t.keyFeatures || product.keyFeatures
  };

  if (t.specs) {
    loc.specs = t.specs;
    loc.specList = Object.entries(t.specs).map(([key, val]) => ({ key, val }));
  }

  if (t.operatingConditions) {
    loc.operatingConditions = t.operatingConditions;
    loc.paramList = Object.entries(t.operatingConditions).map(([key, val]) => ({ key, val }));
  }

  return loc;
};
